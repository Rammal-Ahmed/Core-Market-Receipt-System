# -------------------- CUSTOMER DISCOUNT ----------------------

gross_bill = quantity * product_price

if quantity >= 52:
    discount = gross_bill * 20 / 100
    customer_type = "VIP Customer"
    print("As a VIP Customer, you will receive a 20% discount")

elif quantity >= 35:
    discount = gross_bill * 10 / 100
    customer_type = "Premium Customer"
    print("As a Premium Customer, you will receive a 10% discount")

elif quantity >= 12:
    discount = gross_bill * 5 / 100
    customer_type = "Regular Customer"
    print("As a Regular Customer, you will receive a 5% discount")

else:
    discount = 0
    customer_type = "Regular Customer"


